#!/usr/bin/env python3
"""Generate bellman/syntax/terms.py from dynspec_full.asdl, via pyasdl.

Each ASDL sum becomes a plain base class; each constructor becomes a
frozen dataclass subclassing it, fields in ASDL order, with a tuple for
every sequence slot. One hierarchy is generated: the stored form of
AMD-SG-005 §2a is the only form a term takes (AMD-SG-016 §2). A
qualified field (optional `?` or sequence `*`) gets a default only when
every field after it is qualified too — dataclass rules; construction in
the transformers is positional either way. A constructor with a sequence
slot stores a list given for it as the tuple a term holds, so that a term
written by hand is the value the lowering builds.

Run from anywhere:
    venv/bin/python packages/bellman/gen_types.py
"""

import pathlib
import re

import pyasdl
from pyasdl import FieldQualifier

HERE = pathlib.Path(__file__).parent
_GRAMMARS = HERE / "bellman" / "syntax" / "grammars"
_TERMS = HERE / "bellman" / "syntax" / "terms.py"


def emit(module):
    """The one term module: frozen dataclasses with tuple children, one per
    ASDL constructor, under a plain base class per sort."""
    out = [
        '"""AUTO-GENERATED by gen_types.py from dynspec_full.asdl',
        "— do not edit; edit the ASDL listings and regenerate.",
        "",
        "The terms of Bellman-SYM: one constructor per ASDL constructor,",
        "frozen, with tuple children, so that a term is a hashable value the",
        "lowering builds once and a stage version owns (AMD-SG-005 §2a;",
        "AMD-SG-016 §2). A constructor with a sequence slot stores a list",
        "given for it as the tuple a term holds, so that a term written by",
        "hand — by a test, by the second parsing route, by dataclasses.replace",
        '— is the same value as the one the lowering builds."""',
        "",
        "from dataclasses import dataclass",
        "",
        "",
    ]
    for typ in module.body:
        if not isinstance(typ.value, pyasdl.Sum):
            raise NotImplementedError(f"product type {typ.name}")
        out.append(f"class {typ.name}:")
        out.append("    __slots__ = ()")
        out.append("")
        out.append("")
        for con in typ.value.types:
            out.append("@dataclass(frozen=True, slots=True)")
            out.append(f"class {con.name}({typ.name}):")
            if not con.fields:
                out.append("    pass")
            else:
                qualified = [f.qualifier is not None for f in con.fields]
                # defaults only on the all-qualified tail
                tail = len(con.fields)
                while tail > 0 and qualified[tail - 1]:
                    tail -= 1
                for i, f in enumerate(con.fields):
                    if i >= tail and f.qualifier is FieldQualifier.SEQUENCE:
                        out.append(f"    {f.name}: tuple = ()")
                    elif i >= tail and f.qualifier is FieldQualifier.OPTIONAL:
                        out.append(f"    {f.name}: object = None")
                    elif f.qualifier is FieldQualifier.SEQUENCE:
                        out.append(f"    {f.name}: tuple")
                    else:
                        out.append(f"    {f.name}: object")
                sequences = [f.name for f in con.fields
                             if f.qualifier is FieldQualifier.SEQUENCE]
                if sequences:
                    names = ", ".join(f'"{name}"' for name in sequences)
                    out.append("")
                    out.append("    def __post_init__(self):")
                    out.append(f"        for slot in ({names},):")
                    out.append("            value = getattr(self, slot)")
                    out.append("            if type(value) is list:")
                    out.append("                object.__setattr__(self, slot, tuple(value))")
            out.append("")
            out.append("")
    return "\n".join(out).rstrip() + "\n"


def main():
    source = (_GRAMMARS / "dynspec_full.asdl").read_text()
    source = re.sub(r"--[^\n]*", "", source)   # pyasdl.parse rejects comments
    module = pyasdl.parse(source)
    _TERMS.write_text(emit(module))
    n = sum(len(t.value.types) for t in module.body)
    print(f"terms.py: {n} constructors from {len(module.body)} sorts")


if __name__ == "__main__":
    main()
