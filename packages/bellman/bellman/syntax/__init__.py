"""The `.bl` text of a stage, the parsed AST it lowers to, the words every
other folder reads, and the setting of printed text in columns.

- `grammars/`: the Lark grammar of the language, `stage.lark`, and the ASDL
  listings, the descriptions of its terms from which `terms` and part of
  `typing/typed_expressions.py` are generated.
- `parse`: the parser, from `.bl` text to a Lark parse tree.
- `lower`: the lowering of a parse tree to the parsed AST, the abstract
  syntax tree of the file, with the table of source positions
  (`parse_with_spans`), and the term JSON encoding (`to_json`).
- `terms`: the classes of the parsed AST, one for each constructor of the
  ASDL listing, generated by `packages/bellman/gen_types.py`.
- `decode`: the inverse of `to_json`.
- `source`: the printer that writes a retained term back as `.bl` text.
- `vocabulary`: the words of the language, each written once: the perches
  and their marks, the roles of a field and of a line, the value roles and
  the primitive sets.
- `layout`: the layout engine, which sets a card's document at a width, and
  the width of 78 columns, the heavy rule and the label column that every
  sheet reads.
- `walk`: the values directly inside a term or a record, `children`, and every
  value inside it, `nodes`, which every walk over a term reads.
"""
